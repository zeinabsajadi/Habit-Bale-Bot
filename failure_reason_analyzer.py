# تابع اصلی: تحلیل متن و برگرداندن پاسخ
# ======================================================

def analyze_failure_reason(user_text: str) -> tuple[str, str]:
    """
    نسخه حرفه‌ای:
    - multi-label detection
    - جلوگیری از match اشتباه
    - scoring بهتر
    """

    text = normalize(user_text)

    matched_rules = []

    for rule in RULES:
        if rule["id"] == "unknown":
            continue

        score = 0

        for keyword in rule["keywords"]:
            # match دقیق‌تر با boundary ساده
            if f" {keyword} " in f" {text} ":
                score += 2
            elif keyword in text:
                score += 1

        if score > 0:
            matched_rules.append((rule, score))

    # هیچ چیزی match نشد
    if not matched_rules:
        unknown_rule = next(r for r in RULES if r["id"] == "unknown")
        return "unknown", random.choice(unknown_rule["responses"])

    # مرتب‌سازی بر اساس score
    matched_rules.sort(key=lambda x: x[1], reverse=True)

    best_rule, best_score = matched_rules[0]

    # اگر چند دلیل قوی داشت → ترکیبی رفتار کن
    if len(matched_rules) > 1 and matched_rules[1][1] >= best_score - 1:
        # هنوز هم یه پاسخ می‌دیم (ساده نگه می‌داریم)
        return best_rule["id"], random.choice(best_rule["responses"])

    return best_rule["id"], random.choice(best_rule["responses"])


