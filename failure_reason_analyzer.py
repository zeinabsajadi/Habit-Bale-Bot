def is_skip_message(text: str) -> bool:
    """
    چک می‌کنه که آیا کاربر می‌خواد رد کنه یا نه
    """
    skip_keywords = [
        "رد کن", "رد", "نمی‌خوام", "نمیخوام", "مهم نیست",
        "بی‌خیال", "بیخیال", "skip", "بگذر", "بگذریم", "بی خیال"
    ]
    text_lower = text.strip().lower()
    return any(kw in text_lower for kw in skip_keywords)