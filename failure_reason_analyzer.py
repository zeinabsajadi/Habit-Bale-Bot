def normalize(text: str) -> str:
    """
    نرمال‌سازی متن فارسی برای افزایش دقت match
    """
    text = text.strip().lower()

    # حذف نیم‌فاصله
    text = text.replace("‌", " ")

    # یکسان‌سازی حروف عربی/فارسی
    text = text.replace("ي", "ی").replace("ك", "ک")

    # حذف فاصله‌های اضافی
    text = " ".join(text.split())

    return text

